"""Build content.js from the published build records (BUILD/out/*.json + manifest.json).

Only real pages and real anchors are emitted: URLs come from the manifest, section anchors from the
headings' _element_id, questions from the published accordions, and the link graph from the hrefs
inside each page. Run from the repo root: python3 prototype/hybrid-v2/tools/extract_content.py
"""
import html, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "BUILD" / "out"
DEST = Path(__file__).resolve().parents[1] / "content.js"
manifest = json.loads((OUT / "manifest.json").read_text(encoding="utf-8"))
URL = {m["pid"]: "/" + m["slug"] + "/" if m["slug"] else "/" for m in manifest}
BY_URL = {v: k for k, v in URL.items()}

def text(h):
    h = re.sub(r"<sup>.*?</sup>", "", h or "", flags=re.S)
    t = re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", h))).strip()
    return re.sub(r"\(\s+", "(", re.sub(r"\s+([;,.:)!?])", r"\1", t))

pages = []
for m in manifest:
    pid = m["pid"]
    data = json.loads((OUT / f"{pid}.json").read_text(encoding="utf-8"))
    secs, faqs, links, texts, tables = [], [], set(), [], []
    short = None
    lead = ""
    ordered = False
    def walk(els):
        global_short = None
        for e in els:
            s = e.get("settings", {}); t = e.get("widgetType")
            if t == "heading" and s.get("header_size") == "h2" and s.get("_element_id"):
                secs.append({"id": s["_element_id"], "title": text(s.get("title"))})
            for h in (s.get("editor"), s.get("html")):
                for tb in re.findall(r"<table.*?</table>", h or "", re.S):
                    head = [text(x) for x in re.findall(r"<thead>.*?</thead>", tb, re.S) and re.findall(r"<th[^>]*>(.*?)</th>", re.findall(r"<thead>(.*?)</thead>", tb, re.S)[0], re.S)]
                    body = re.findall(r"<tbody>(.*?)</tbody>", tb, re.S)
                    rows = []
                    for tr in re.findall(r"<tr>(.*?)</tr>", body[0] if body else tb, re.S):
                        cells = [re.sub(r"\s*\[\w+\]", "", text(c)) for c in re.findall(r"<t[hd][^>]*>(.*?)</t[hd]>", tr, re.S)]
                        if cells and cells != head: rows.append(cells)
                    tables.append({"section": secs[-1]["id"] if secs else None, "head": [re.sub(r"\s*\[\w+\]", "", x) for x in head], "rows": rows})
            if t == "accordion":
                for tab in s.get("tabs", []):
                    faqs.append({"q": text(tab.get("tab_title")), "a": text(tab.get("tab_content"))[:420]})
            for h in (s.get("editor"), s.get("html"), s.get("title")):
                if h:
                    for href in re.findall(r'href="(/[a-z0-9/-]*)(#[^"]*)?"', h):
                        if href[0] in BY_URL and href[0] != URL[pid]:
                            links.add(href[0])
                    if t == "text-editor": texts.append(h)
            walk(e.get("elements", []))
    walk(data)
    joined = " ".join(texts)
    for h in texts:
        sm = re.search(r"Short answer\s*(:\s*</strong>|</strong>\s*:?|:|(?=\())", h)
        if not sm:
            continue
        body = h[sm.end():]
        items = re.findall(r"<li>(.*?)</li>", body, re.S)
        lead = text(re.sub(r"^[\s:]*(</strong>)?", "", re.split(r"<[uo]l", body)[0])).lstrip(": ") if items else ""
        ordered = "<ol" in body
        short = [text(i) for i in items] if items else [text(body)]
        short = [x.lstrip(": ").strip() for x in short if x.strip(": ").strip()]
        break
    intent = None
    mi = re.search(r"<p[^>]*>(.*?)</p>", joined, re.S)
    if mi: intent = text(mi.group(1))
    pages.append({
        "pid": pid, "url": URL[pid], "title": m["wp_title"], "h1": re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", m["h1"])),
        "seo": m["seo_title"], "meta": m["meta"], "crumb": m["breadcrumb"], "intent": intent,
        "short": short, "lead": lead, "ordered": ordered, "sections": secs, "faqs": faqs, "links": sorted(links), "tables": tables,
    })

DEST.write_text("/* GENERATED by tools/extract_content.py from BUILD/out (the published build records). Do not edit. */\n"
                "window.GD_PAGES = " + json.dumps(pages, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
print("pages", len(pages), "sections", sum(len(p["sections"]) for p in pages), "faqs", sum(len(p["faqs"]) for p in pages),
      "links", sum(len(p["links"]) for p in pages), "short answers", sum(1 for p in pages if p["short"]))
for p in pages: print(p["pid"], p["url"], len(p["sections"]), "secs", len(p["faqs"]), "faqs", len(p["links"]), "links", "| short:", (p["short"] or ["-"])[0][:60])
